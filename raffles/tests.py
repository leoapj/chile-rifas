class ConcurrencyTests(ThrottleResetMixin, TransactionTestCase):
    """Solo es significativo en PostgreSQL (SQLite ignora select_for_update)."""

    def test_two_simultaneous_buyers_only_one_wins(self):
        if connection.vendor != "postgresql":
            self.skipTest("Requiere PostgreSQL")
        raffle = make_raffle()
        results, barrier = [], threading.Barrier(8)

        def buy(i):
            from django.test import Client
            from django.db import connection as conn
            try:
                barrier.wait()
                res = Client().post(
                    reverse("payment-reserve"),
                    {"raffle_id": raffle.id, "ticket_numbers": [7], **BUYER, "buyer_name": f"Comprador {i}"},
                    content_type="application/json",
                )
                results.append(res.status_code)
            finally:
                conn.close()

        threads = [threading.Thread(target=buy, args=(i,)) for i in range(8)]
        [t.start() for t in threads]
        [t.join() for t in threads]
        self.assertEqual(sorted(results), [201] + [409] * 7)
        self.assertEqual(Payment.objects.count(), 1)


