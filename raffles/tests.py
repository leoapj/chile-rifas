class PerRaffleAccountsTests(ThrottleResetMixin, TestCase):
    def _reserve(self, raffle):
        res = self.client.post(
            reverse("payment-reserve"),
            {"raffle_id": raffle.id, "ticket_numbers": [1], **BUYER}, content_type="application/json",
        )
        return Payment.objects.get(public_id=res.json()["public_id"])

    def test_each_raffle_shows_its_own_account_and_general_is_fallback(self):
        general = BankAccount.objects.create(bank_name="Banco General", account_type="rut", account_number="111",
                                             holder_name="Yo", holder_rut="1-9")
        maria = BankAccount.objects.create(bank_name="Banco de María", account_type="vista", account_number="222",
                                           holder_name="María", holder_rut="2-7")
        mine = make_raffle()
        hers = Raffle.objects.create(name="Rifa de María", slug="maria", price_clp=500, total_tickets=5,
                                     status="active", draw_date=timezone.now() + timedelta(days=3),
                                     organizer_name="María Pérez")
        hers.bank_accounts.add(maria)

        page_mine = self.client.get(f"/pago/{self._reserve(mine).public_id}/")
        self.assertContains(page_mine, "Banco General")
        self.assertNotContains(page_mine, "Banco de María")   # la cuenta de María no aparece en mi rifa

        page_hers = self.client.get(f"/pago/{self._reserve(hers).public_id}/")
        self.assertContains(page_hers, "Banco de María")
        self.assertNotContains(page_hers, "Banco General")

        self.assertContains(self.client.get("/"), "Organiza: María Pérez")
        detail = self.client.get("/rifa/maria/")
        self.assertContains(detail, 'property="og:title"')
        self.assertContains(detail, "Organiza: María Pérez")

    def test_proof_email_names_the_account_to_check(self):
        from django.core import mail
        cfg = SiteConfiguration.load(); cfg.admin_notification_email = "yo@correo.cl"; cfg.save()
        acc = BankAccount.objects.create(bank_name="Banco de María", account_type="vista", account_number="222",
                                         holder_name="María", holder_rut="2-7")
        raffle = make_raffle(); raffle.bank_accounts.add(acc)
        payment = self._reserve(raffle)
        with self.captureOnCommitCallbacks(execute=True):
            payment.submit_proof("99887766")
        self.assertIn("Banco de María", mail.outbox[0].body)


