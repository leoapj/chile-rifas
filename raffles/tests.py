        self.assertContains(page_hers, "Banco de María")
        self.assertNotContains(page_hers, "Banco General")

        self.assertContains(self.client.get("/"), "Organiza: María Pérez")
        detail = self.client.get("/rifa/maria/")
        self.assertContains(detail, 'property="og:title"')
        self.assertContains(detail, "Organiza: María Pérez")

