BUYER = {"buyer_name": "Juan Pérez", "buyer_phone": "+56 9 1234 5678", "buyer_email": ""}


class ThrottleResetMixin:
    """El rate limit de DRF usa la caché; se limpia para que un test no afecte al siguiente."""

    def setUp(self):
        cache.clear()
        super().setUp()


def make_raffle(total=10, price=2000):
    return Raffle.objects.create(
        name="Premio", slug="premio", price_clp=price, total_tickets=total,
        status=Raffle.Status.ACTIVE, draw_date=timezone.now() + timedelta(days=7),
    )


class ReserveFlowTests(ThrottleResetMixin, TestCase):
    def setUp(self):
        super().setUp()
        self.raffle = make_raffle()
        self.url = reverse("payment-reserve")

    def reserve(self, numbers, **extra):
        return self.client.post(
            self.url,
            {"raffle_id": self.raffle.id, "ticket_numbers": numbers, **BUYER, **extra},
            content_type="application/json",
        )

    def test_tickets_autogenerated(self):
        self.assertEqual(self.raffle.tickets.count(), 10)

    def test_reserve_calculates_clp_amount_server_side(self):
        res = self.reserve([1, 2, 3])
        self.assertEqual(res.status_code, 201)
        self.assertEqual(res.json()["amount"], 6000)
        payment = Payment.objects.get()
        self.assertEqual(payment.buyer_phone, "+56912345678")  # normalizado
        self.assertEqual(self.raffle.tickets.filter(status="reserved").count(), 3)
        self.assertTrue(res.json()["reference_code"].startswith("RIFA-"))

    def test_second_buyer_cannot_take_same_number(self):
        self.assertEqual(self.reserve([1, 2]).status_code, 201)
        res = self.reserve([2, 3])
        self.assertEqual(res.status_code, 409)
        self.assertEqual(self.raffle.tickets.get(number=3).status, "available")  # nada quedó a medias

    def test_rejects_invalid_phone_and_too_many_tickets(self):
        self.assertEqual(self.reserve([1], buyer_phone="12345").status_code, 400)
        cfg = SiteConfiguration.load()
        cfg.max_tickets_per_purchase = 2
        cfg.save()
        self.assertEqual(self.reserve([1, 2, 3]).status_code, 400)

    def test_unknown_number_rejected(self):
        self.assertEqual(self.reserve([99]).status_code, 409)

    def test_expired_reservation_is_released_for_next_buyer(self):
        self.reserve([5])
        Ticket.objects.filter(number=5).update(reserved_until=timezone.now() - timedelta(minutes=1))
        Payment.objects.update(expires_at=timezone.now() - timedelta(minutes=1))
        self.assertEqual(self.reserve([5]).status_code, 201)
        self.assertEqual(Payment.objects.filter(status="expired").count(), 1)


class ProofAndConfirmationTests(ThrottleResetMixin, TestCase):
    def setUp(self):
        super().setUp()
        self.raffle = make_raffle()
        res = self.client.post(
            reverse("payment-reserve"),
            {"raffle_id": self.raffle.id, "ticket_numbers": [1, 2], **BUYER},
            content_type="application/json",
        )
        self.payment = Payment.objects.get(public_id=res.json()["public_id"])

    def send_proof(self, ref="123456789"):
        return self.client.post(
            reverse("payment-submit-proof", args=[self.payment.public_id]),
            {"buyer_reference": ref}, content_type="application/json",
        )

    def test_proof_extends_reservation(self):
        before = self.payment.expires_at
        self.assertEqual(self.send_proof().status_code, 200)
        self.payment.refresh_from_db()
        self.assertGreater(self.payment.expires_at, before + timedelta(hours=23))
        self.assertTrue(all(t.reserved_until > before + timedelta(hours=23) for t in self.payment.tickets.all()))
        # un comprobante enviado ya no se libera con la limpieza automática
        release_expired_reservations()
        self.assertEqual(self.raffle.tickets.filter(status="reserved").count(), 2)

    def test_proof_rejected_after_expiry(self):
        Payment.objects.update(expires_at=timezone.now() - timedelta(seconds=1))
        self.assertEqual(self.send_proof().status_code, 409)

    def test_short_reference_rejected(self):
        self.assertEqual(self.send_proof("1").status_code, 400)

    def test_confirm_marks_tickets_paid(self):
        self.payment.mark_completed()
        self.payment.refresh_from_db()
        self.assertEqual(self.payment.status, "completed")
        self.assertEqual(self.raffle.tickets.filter(status="paid").count(), 2)

    def test_reject_releases_tickets(self):
        self.payment.mark_failed()
        self.assertEqual(self.raffle.tickets.filter(status="available").count(), 10)

    def test_late_transfer_can_be_confirmed_if_numbers_still_free(self):
        Payment.objects.update(expires_at=timezone.now() - timedelta(minutes=1))
        Ticket.objects.update(reserved_until=timezone.now() - timedelta(minutes=1))
        release_expired_reservations()
        self.payment.refresh_from_db()
        self.assertEqual(self.payment.status, "expired")
        self.payment.mark_completed()
        self.assertEqual(self.raffle.tickets.filter(status="paid", buyer_name="Juan Pérez").count(), 2)

    def test_late_transfer_blocked_if_someone_else_took_number(self):
        Payment.objects.update(expires_at=timezone.now() - timedelta(minutes=1))
        Ticket.objects.update(reserved_until=timezone.now() - timedelta(minutes=1))
        other = self.client.post(
            reverse("payment-reserve"),
            {"raffle_id": self.raffle.id, "ticket_numbers": [2], **BUYER, "buyer_name": "Otra Persona"},
            content_type="application/json",
        )
        self.assertEqual(other.status_code, 201)
        self.payment.refresh_from_db()
        with self.assertRaises(PaymentStateError):
            self.payment.mark_completed()
        self.assertEqual(self.raffle.tickets.get(number=2).buyer_name, "Otra Persona")
        self.assertEqual(self.raffle.tickets.get(number=1).status, "available")  # sin cambios

    def test_cannot_reject_completed_payment(self):
        self.payment.mark_completed()
        with self.assertRaises(PaymentStateError):
            self.payment.mark_failed()


class NotificationTests(ThrottleResetMixin, TestCase):
    def setUp(self):
        super().setUp()
        from django.core import mail
        self.mail = mail
        self.raffle = make_raffle(total=2)
        cfg = SiteConfiguration.load()
        cfg.admin_notification_email = "yo@correo.cl"
        cfg.save()
        res = self.client.post(
            reverse("payment-reserve"),
            {"raffle_id": self.raffle.id, "ticket_numbers": [1, 2], **BUYER}, content_type="application/json",
        )
        self.payment = Payment.objects.get(public_id=res.json()["public_id"])

    def test_email_on_proof_and_when_raffle_sold_out(self):
        with self.captureOnCommitCallbacks(execute=True):
            self.client.post(
                reverse("payment-submit-proof", args=[self.payment.public_id]),
                {"buyer_reference": "55667788"}, content_type="application/json",
            )
        self.assertEqual(len(self.mail.outbox), 1)
        self.assertEqual(self.mail.outbox[0].to, ["yo@correo.cl"])
        self.assertIn(self.payment.reference_code, self.mail.outbox[0].subject)
        with self.captureOnCommitCallbacks(execute=True):
            self.payment.mark_completed()
        # rifa de 2 números, ambos pagados: llega el aviso del 50% y el de "completa"
        subjects = [m.subject for m in self.mail.outbox[1:]]
        self.assertEqual(len(subjects), 2)
        self.assertTrue(any("50% vendido" in x for x in subjects))
        self.assertTrue(any("Rifa completa" in x for x in subjects))

    def test_no_email_without_configured_address_and_failures_dont_break(self):
        SiteConfiguration.objects.update(admin_notification_email="")
        with self.captureOnCommitCallbacks(execute=True):
            self.payment.submit_proof("55667788")
        self.assertEqual(len(self.mail.outbox), 0)


class HalfSoldTests(ThrottleResetMixin, TestCase):
    def test_half_sold_email_sent_once(self):
        from django.core import mail
        cfg = SiteConfiguration.load()
        cfg.admin_notification_email = "yo@correo.cl"
        cfg.save()
        raffle = make_raffle(total=10)

        def buy_and_confirm(numbers):
            res = self.client.post(
                reverse("payment-reserve"),
                {"raffle_id": raffle.id, "ticket_numbers": numbers, **BUYER}, content_type="application/json",
            )
            payment = Payment.objects.get(public_id=res.json()["public_id"])
            with self.captureOnCommitCallbacks(execute=True):
                payment.mark_completed()

        buy_and_confirm([1, 2, 3, 4])
        self.assertEqual(len(mail.outbox), 0)           # 40%: todavía no
        buy_and_confirm([5])
        self.assertEqual(len(mail.outbox), 1)           # 50%: aviso
        self.assertIn("50% vendido", mail.outbox[0].subject)
        buy_and_confirm([6, 7])
        self.assertEqual(len(mail.outbox), 1)           # 70%: no se repite


